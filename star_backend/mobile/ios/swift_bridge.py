from typing import Dict, Any, List, Optional


class SwiftNativeBridge:
    """
    Manages C ABI function declarations, Swift runtime bindings, and data marshalling
    between the iOS UIKit/Swift runtime and StarVM / MobileRuntime engine.
    """

    @classmethod
    def get_c_abi_signatures(cls) -> Dict[str, str]:
        return {
            "star_ios_init_runtime": "bool star_ios_init_runtime(const char* app_name, float width, float height, float scale)",
            "star_ios_load_bytecode": "bool star_ios_load_bytecode(const uint8_t* bytes, size_t length)",
            "star_ios_dispatch_touch": "void star_ios_dispatch_touch(int phase, int touch_id, float x, float y, float force)",
            "star_ios_render_frame": "const char* star_ios_render_frame(void)",
            "star_ios_dispatch_lifecycle": "void star_ios_dispatch_lifecycle(const char* state)",
            "star_ios_dispatch_back_press": "bool star_ios_dispatch_back_press(void)",
            "star_ios_set_safe_area": "void star_ios_set_safe_area(float top, float bottom, float left, float right)"
        }

    @classmethod
    def generate_c_header(cls) -> str:
        return """/*
 * Star iOS C ABI Header
 * Auto-generated by Star Compiler Toolchain
 */

#ifndef STAR_IOS_RUNTIME_H
#define STAR_IOS_RUNTIME_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#ifdef __cplusplus
extern "C" {
#endif

bool star_ios_init_runtime(const char* app_name, float width, float height, float scale);
bool star_ios_load_bytecode(const uint8_t* bytes, size_t length);
void star_ios_dispatch_touch(int phase, int touch_id, float x, float y, float force);
const char* star_ios_render_frame(void);
void star_ios_dispatch_lifecycle(const char* state);
bool star_ios_dispatch_back_press(void);
void star_ios_set_safe_area(float top, float bottom, float left, float right);

#ifdef __cplusplus
}
#endif

#endif // STAR_IOS_RUNTIME_H
"""

    @classmethod
    def generate_swift_bridge_source(cls) -> str:
        return """import Foundation

public final class StarNativeBridge {
    public static let shared = StarNativeBridge()

    private init() {}

    @discardableResult
    public func initRuntime(appName: String, width: Float, height: Float, scale: Float) -> Bool {
        return appName.withCString { namePtr in
            return star_ios_init_runtime(namePtr, width, height, scale)
        }
    }

    @discardableResult
    public func loadBytecode(_ data: Data) -> Bool {
        return data.withUnsafeBytes { rawBuffer in
            guard let baseAddr = rawBuffer.baseAddress?.assumingMemoryBound(to: UInt8.self) else { return false }
            return star_ios_load_bytecode(baseAddr, rawBuffer.count)
        }
    }

    public func dispatchTouch(phase: Int, touchId: Int, x: Float, y: Float, force: Float = 1.0) {
        star_ios_dispatch_touch(Int32(phase), Int32(touchId), x, y, force)
    }

    public func renderFrame() -> String {
        if let cStr = star_ios_render_frame() {
            return String(cString: cStr)
        }
        return "[]"
    }

    public func dispatchLifecycle(_ state: String) {
        state.withCString { statePtr in
            star_ios_dispatch_lifecycle(statePtr)
        }
    }

    public func dispatchBackPress() -> Bool {
        return star_ios_dispatch_back_press()
    }

    public func setSafeArea(top: Float, bottom: Float, left: Float, right: Float) {
        star_ios_set_safe_area(top, bottom, left, right)
    }
}
"""
