class AndroidJNIBridge:
    """
    Manages JNI symbol declarations, C++ NDK bindings, and data marshalling
    between the Android JVM runtime and the StarVM / MobileRuntime engine.
    """
    JNI_PACKAGE = "org/starlang/runtime"
    JNI_CLASS = "StarNativeBridge"

    @classmethod
    def get_jni_signatures(cls) -> Dict[str, str]:
        return {
            "initRuntime": "(Ljava/lang/String;IIF)Z",
            "loadBytecode": "([B)Z",
            "dispatchTouchEvent": "(IIFF)V",
            "renderFrame": "()[B",
            "dispatchLifecycle": "(Ljava/lang/String;)V",
            "dispatchBackPress": "()Z",
            "setScreenMetrics": "(IIFFLjava/lang/String;)V"
        }

    @classmethod
    def generate_cpp_jni_source(cls) -> str:
        return """/*
 * Star Android Native NDK Bridge (C++20)
 * Auto-generated by Star Compiler Toolchain
 */

#include <jni.h>
#include <string>
#include <vector>
#include <memory>
#include <android/log.h>

#define LOG_TAG "StarNative"
#define LOGI(...) __android_log_print(ANDROID_LOG_INFO, LOG_TAG, __VA_ARGS__)
#define LOGE(...) __android_log_print(ANDROID_LOG_ERROR, LOG_TAG, __VA_ARGS__)

extern "C" {

JNIEXPORT jboolean JNICALL
Java_org_starlang_runtime_StarNativeBridge_initRuntime(
    JNIEnv* env, jobject thiz, jstring app_name, jint width, jint height, jfloat density) {
    const char* name = env->GetStringUTFChars(app_name, nullptr);
    LOGI("StarVM Mobile Runtime Initialized for %s (%dx%d @ %.1fx)", name, width, height, density);
    env->ReleaseStringUTFChars(app_name, name);
    return JNI_TRUE;
}

JNIEXPORT jboolean JNICALL
Java_org_starlang_runtime_StarNativeBridge_loadBytecode(
    JNIEnv* env, jobject thiz, jbyteArray bytecode) {
    jsize len = env->GetArrayLength(bytecode);
    LOGI("StarVM Loading %d bytes of bytecode container", len);
    return JNI_TRUE;
}

JNIEXPORT void JNICALL
Java_org_starlang_runtime_StarNativeBridge_dispatchTouchEvent(
    JNIEnv* env, jobject thiz, jint phase, jint pointer_id, jfloat x, jfloat y) {
    // Forward touch event to Star Gesture Engine
}

JNIEXPORT jbyteArray JNICALL
Java_org_starlang_runtime_StarNativeBridge_renderFrame(
    JNIEnv* env, jobject thiz) {
    // Returns serialized MobileDrawCommand stream buffer
    const char* empty_stream = "[]";
    jsize len = strlen(empty_stream);
    jbyteArray result = env->NewByteArray(len);
    env->SetByteArrayRegion(result, 0, len, (const jbyte*)empty_stream);
    return result;
}

JNIEXPORT void JNICALL
Java_org_starlang_runtime_StarNativeBridge_dispatchLifecycle(
    JNIEnv* env, jobject thiz, jstring state) {
    const char* state_str = env->GetStringUTFChars(state, nullptr);
    LOGI("StarVM Lifecycle Transition -> %s", state_str);
    env->ReleaseStringUTFChars(state, state_str);
}

JNIEXPORT jboolean JNICALL
Java_org_starlang_runtime_StarNativeBridge_dispatchBackPress(
    JNIEnv* env, jobject thiz) {
    return JNI_FALSE;
}

} // extern "C"
"""

