    CSC_CANDIDATES = [
        r"C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe",
        r"C:\Windows\Microsoft.NET\Framework\v4.0.30319\csc.exe",
        r"C:\Windows\Microsoft.NET\Framework64\v3.5\csc.exe",
        r"C:\Windows\Microsoft.NET\Framework\v3.5\csc.exe",
    ]

    @classmethod
    def find_csc(cls) -> Optional[str]:
        """Locates csc.exe compiler on the host system."""
        # 1. Check PATH
        which_csc = shutil.which("csc")
        if which_csc:
            return which_csc

        # 2. Check standard Windows Framework paths
        for path in cls.CSC_CANDIDATES:
            if os.path.exists(path):
                return path

        return None

