    @classmethod
    def compile_launcher(
        cls,
        output_exe_path: str,
        command_prefix: str = "",
        platform_target: str = "anycpu",
        version: str = "1.2.0"
    ) -> bool:
        """
        Compiles a single launcher executable using csc.exe.
        platform_target can be 'anycpu', 'x64', or 'x86'.
        """
        csc_exe = cls.find_csc()
        if not csc_exe:
            return False

        cs_source = cls.generate_launcher_csharp(command_prefix, version=version)
        os.makedirs(os.path.dirname(os.path.abspath(output_exe_path)), exist_ok=True)

        temp_cs = os.path.join(tempfile.gettempdir(), f"star_launcher_{os.getpid()}_{os.path.basename(output_exe_path)}.cs")
        try:
            with open(temp_cs, "w", encoding="utf-8") as f:
                f.write(cs_source)

            # Build csc arguments
            cmd = [
                csc_exe,
                "/nologo",
                "/target:exe",
                f"/platform:{platform_target}",
                "/optimize+",
                f"/out:{output_exe_path}",
                temp_cs
            ]

            res = subprocess.run(cmd, capture_output=True, text=True)
            if res.returncode != 0:
                print(f"[PELauncherCompiler] Error compiling {output_exe_path}: {res.stderr or res.stdout}", file=sys.stderr)
                return False

            return os.path.exists(output_exe_path)
        finally:
            if os.path.exists(temp_cs):
                try:
                    os.remove(temp_cs)
                except Exception:
                    pass

    @classmethod
    def compile_all_launchers(
        cls,
        target_dir: str,
        platform_target: str = "anycpu",
        version: str = "1.2.0"
    ) -> Dict[str, str]:
        """
        Compiles all three standard launchers (star.exe, starc.exe, star-runtime.exe)
        into the specified directory.
        """
        launchers = {
            "star.exe": "",
            "starc.exe": "compile",
            "star-runtime.exe": "run"
        }

        results = {}
        for exe_name, prefix in launchers.items():
            dest = os.path.join(target_dir, exe_name)
            success = cls.compile_launcher(dest, command_prefix=prefix, platform_target=platform_target, version=version)
            if success:
                results[exe_name] = dest

        return results

    @classmethod
    def verify_pe_header(cls, exe_path: str) -> Dict[str, any]:
        """
        Inspects the PE headers of an executable to verify that it is a valid
        Windows PE32 or PE32+ binary (not a 16-bit DOS stub or dummy file).
        """
        if not os.path.exists(exe_path):
            return {"valid": False, "error": "File does not exist"}

        with open(exe_path, "rb") as f:
            data = f.read(1024)

        if len(data) < 64:
            return {"valid": False, "error": "File smaller than DOS header (64 bytes)"}

        # Check DOS magic 'MZ'
        if data[:2] != b"MZ":
            return {"valid": False, "error": f"Invalid DOS header: {data[:2]!r}"}

        import struct
        e_lfanew = struct.unpack("<I", data[60:64])[0]
        if len(data) < e_lfanew + 4:
            return {"valid": False, "error": f"File smaller than PE offset {e_lfanew}"}

        pe_sig = data[e_lfanew:e_lfanew + 4]
        if pe_sig != b"PE\x00\x00":
            return {"valid": False, "error": f"Invalid PE signature: {pe_sig!r}"}

        # Read machine type from COFF header (2 bytes after PE signature)
        machine = struct.unpack("<H", data[e_lfanew + 4:e_lfanew + 6])[0]
        # 0x014c = IMAGE_FILE_MACHINE_I386 (x86 / AnyCPU MSIL)
        # 0x8664 = IMAGE_FILE_MACHINE_AMD64 (x64)
        # 0xAA64 = IMAGE_FILE_MACHINE_ARM64
        machine_map = {
            0x014C: "i386 (x86 / AnyCPU MSIL)",
            0x8664: "AMD64 (x64)",
            0xAA64: "ARM64"
        }
        arch_name = machine_map.get(machine, f"Unknown (0x{machine:04x})")

        return {
            "valid": True,
            "dos_header": "MZ",
            "pe_signature": "PE\\0\\0",
            "e_lfanew": e_lfanew,
            "machine_raw": machine,
            "architecture": arch_name,
            "size_bytes": os.path.getsize(exe_path)
        }
